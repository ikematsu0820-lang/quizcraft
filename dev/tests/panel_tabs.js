// 確認用: パネルクイズの作成（スマホ）— ジャンルのタブで1つずつ切り替え
const path = require('path'); const fs = require('fs');
const OUT = path.join(__dirname, 'out'); fs.mkdirSync(OUT, { recursive: true });
const APP = 'file://' + path.resolve(__dirname, '../../index.html');
const FAKEFB = path.resolve(__dirname, '../fakefb.js');
const { chromium } = require(process.env.PLAYWRIGHT || '/opt/node-tools/node_modules/playwright');
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  await ctx.addInitScript({ path: FAKEFB });
  const p = await ctx.newPage();
  p.on('pageerror', e => console.log('ERR', e.message));
  await p.route(/gstatic|googleapis\.com\/(?!css)|jsdelivr/, r => r.abort());
  await p.goto(APP); await p.waitForTimeout(800);
  await p.evaluate(() => window.App.Ui.showView(window.App.Ui.views.selectType));
  await p.evaluate(() => document.querySelector('#select-type-view .type-select-card[data-type="panel_quiz"]').click()); await p.waitForTimeout(400);
  await p.evaluate(() => document.querySelector('#ps-overlay .ps-go')?.click()); await p.waitForTimeout(800);
  const g = () => p.evaluate(() => [...document.querySelectorAll('#pbq-board .pbq-genre')].map(s => getComputedStyle(s).display).join(','));
  console.log('visible', await g());
  await p.fill('#pbq-board .pbq-genre.pbq-on .pbq-gname', '文学');
  await p.fill('#pbq-board .pbq-genre.pbq-on .pbq-q', '「吾輩は猫である」の作者は？');
  await p.fill('#pbq-board .pbq-genre.pbq-on .pbq-a', '夏目漱石');
  await p.evaluate(() => document.querySelector('.pbq-tab[data-k="1"]').click()); await p.waitForTimeout(200);
  console.log('after tab2', await g());
  await p.evaluate(() => document.querySelector('.pbq-tab-add').click()); await p.waitForTimeout(200);
  console.log('after add', await g(), await p.evaluate(() => document.querySelector('.pbq-tab.on').textContent));
  await p.evaluate(() => document.querySelector('.pbq-tab[data-k="0"]').click()); await p.waitForTimeout(200);
  await p.evaluate(() => document.getElementById('pbq-board').scrollIntoView());
  await p.evaluate(() => window.scrollBy(0, -60));
  await p.screenshot({ path: `${OUT}/panel-tabs.png` });
  console.log('read', await p.evaluate(() => JSON.stringify(window.App.PanelBoard.readBoard(false).slice(0, 2))));
  await b.close();
})();
